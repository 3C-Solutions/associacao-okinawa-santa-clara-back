BEGIN;
SET LOCAL lock_timeout = '5s';
CREATE TABLE IF NOT EXISTS public.entradas_financeiras (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_entrada DATE NOT NULL,
    descricao VARCHAR(200) NOT NULL CHECK (char_length(trim(descricao)) >= 3),
    categoria VARCHAR(100) NOT NULL CHECK (char_length(trim(categoria)) > 0),
    valor NUMERIC(14,2) NOT NULL CHECK (valor > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('Recebido', 'Pendente')),
    fk_usuario INTEGER NOT NULL REFERENCES public.usuario(id),
    fk_familia INTEGER REFERENCES public.familia(id)
);
COMMIT;

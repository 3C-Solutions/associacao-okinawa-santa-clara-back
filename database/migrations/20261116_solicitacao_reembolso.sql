BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS public.solicitacao_reembolso (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_usuario INTEGER NOT NULL,
    motivo VARCHAR(500) NOT NULL CHECK (char_length(trim(motivo)) >= 5),
    valor NUMERIC(14,2) NOT NULL CHECK (valor > 0),
    comprovante_nome VARCHAR(255) NOT NULL,
    comprovante_tipo VARCHAR(50) NOT NULL
        CHECK (comprovante_tipo IN ('image/png', 'image/jpeg', 'image/webp', 'application/pdf')),
    comprovante_dados TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pendente'
        CHECK (status IN ('Pendente', 'Aprovado', 'Pago', 'Recusado')),
    data_solicitacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_revisao TIMESTAMP,
    motivo_recusa VARCHAR(500),
    fk_revisor INTEGER,
    CONSTRAINT fk_solicitacao_reembolso_usuario
        FOREIGN KEY (fk_usuario) REFERENCES public.usuario(id),
    CONSTRAINT fk_solicitacao_reembolso_revisor
        FOREIGN KEY (fk_revisor) REFERENCES public.usuario(id)
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_solicitacao_reembolso_usuario'
    ) THEN
        ALTER TABLE public.solicitacao_reembolso
            ADD CONSTRAINT fk_solicitacao_reembolso_usuario
            FOREIGN KEY (fk_usuario) REFERENCES public.usuario(id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_solicitacao_reembolso_revisor'
    ) THEN
        ALTER TABLE public.solicitacao_reembolso
            ADD CONSTRAINT fk_solicitacao_reembolso_revisor
            FOREIGN KEY (fk_revisor) REFERENCES public.usuario(id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_solicitacao_reembolso_usuario_data
    ON public.solicitacao_reembolso (fk_usuario, data_solicitacao DESC);
CREATE INDEX IF NOT EXISTS ix_solicitacao_reembolso_status_data
    ON public.solicitacao_reembolso (status, data_solicitacao DESC);

ALTER TABLE public.despesas
    ADD COLUMN IF NOT EXISTS fk_reembolso INTEGER;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_despesas_solicitacao_reembolso'
    ) THEN
        ALTER TABLE public.despesas
            ADD CONSTRAINT fk_despesas_solicitacao_reembolso
            FOREIGN KEY (fk_reembolso) REFERENCES public.solicitacao_reembolso(id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_despesas_fk_reembolso'
    ) THEN
        ALTER TABLE public.despesas
            ADD CONSTRAINT uq_despesas_fk_reembolso UNIQUE (fk_reembolso);
    END IF;
END $$;

COMMIT;
